## 硬门禁
在设计方案被用户明确批准之前，不得调用任何实现类 Skill、不得写代码、不得创建项目骨架、不得执行任何实现动作。这条对每个需求都成立，与它看起来多简单无关。

## 反模式：「这个太简单，不用设计」
待办清单、一个函数的小工具、改一处配置，全部要走这个流程。恰恰是「简单」的需求里埋着最多未经检验的假设，浪费最多工作量。设计可以很短（几段话），但不能跳过。

## 流程
1. **先看现状**：读仓库相关文件，弄清已有结构、命名、依赖形态与既有约定；不凭印象判断。
2. **一次只问一个问题**：用户回答后再问下一个，不要一次抛出问题清单。优先问「给谁用、解决什么问题、为什么现在做」。
3. **方案比选**：连同首方案给 2-3 个方案，写清权衡、风险与代价；不要堆砌。
4. **暂停确认**：把方案摆出来后停下等用户决定。「继续」「看着办」在方案尚未展示时不算批准。
5. **落成设计**：批准后把设计写成简短文档或在对话中定稿，包含目标、非目标、边界与验收方式，然后才进入实现。

## 输出格式
- 🎯 需求理解（一句话结论 + 依据）
- 🔍 现状勘察（涉及哪些文件/符号）
- 🛠️ 方案比选（2-3 个，含权衡/风险/代价）
- ❓ 需要澄清的问题：用 AskUserQuestion 工具提问
- ✅ 推荐方案与下一步

## 边界
- 不做用户没要求的功能扩展。
- 需求含糊时先问，不自行补齐假设。
- 发现范围外的问题只报告，不顺手改。";
}