namespace LuBan.DI;

/// <summary>
/// 容器模式。
/// </summary>
internal enum DiContainerMode
{
    /// <summary>
    /// 宿主根：可注册、可构建。
    /// </summary>
    Root,

    /// <summary>
    /// 外部 provider 包装视图：只解析。
    /// </summary>
    ProviderView,

    /// <summary>
    /// 外部集合包装视图：只注册、不可构建。
    /// </summary>
    CollectionView,

    /// <summary>
    /// 由 CreateScope 派生的作用域容器：只解析。
    /// </summary>
    Scope
}